import { mkdir, copyFile, cp, rm, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const out = path.join(root, 'dist');
if (out !== path.join(root, 'dist')) throw new Error('构建目录不符合预期');
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await copyFile(path.join(root, 'index.html'), path.join(out, 'index.html'));
await cp(path.join(root, 'src'), path.join(out, 'src'), { recursive: true });
await cp(path.join(root, 'assets'), path.join(out, 'assets'), { recursive: true });
await copyFile(path.join(root, 'index.html'), path.join(out, '404.html'));
console.log('静态构建完成：dist/，支持 GitHub Pages 仓库子路径。');
